delimiter //
/*que no haya más de 2 recolectores en una cuadrilla*/
create trigger check_max_recolectores_cuadrilla
before insert on cuadrilla_recolector
for each row
begin
    declare cantidad_actual int;

    -- contamos cuántos recolectores ya tiene asignados la cuadrilla
    select count(*) 
    into cantidad_actual
    from cuadrilla_recolector
    where cuad_id = new.cuad_id;

    -- si ya hay 2 o más, frenamos la inserción
    if cantidad_actual >= 2 then
        signal sqlstate '45000'
        set message_text = 'error: la cuadrilla ya tiene el límite máximo de 2 recolectores asignados.';
    end if;
end //

delimiter ;

/*Lo mismo pero en caso de actualizar*/
delimiter //

create trigger check_max_recolectores_cuadrilla_update 
before update on cuadrilla_recolector
for each row
begin
    declare cantidad_actual int;

    -- solo validamos si efectivamente le están cambiando la cuadrilla al recolector
    if new.cuad_id <> old.cuad_id then
        select count(*) 
        into cantidad_actual
        from cuadrilla_recolector
        where cuad_id = new.cuad_id;

        if cantidad_actual >= 2 then
            signal sqlstate '45000'
            set message_text = 'error: la cuadrilla de destino ya tiene 2 recolectores asignados.';
        end if;
    end if;
end //

