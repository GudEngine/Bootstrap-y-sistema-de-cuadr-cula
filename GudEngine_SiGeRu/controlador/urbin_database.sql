create table if not exists contenedor(
cont_id int auto_increment primary key,
cont_activo boolean default true,
cont_latitud DECIMAL(10, 8) NOT NULL,
cont_longitud DECIMAL(11, 8) NOT NULL,
cont_calle varchar(29) ,
cont_estado varchar(10),
cont_tipo varchar(9),
check (cont_estado in('funcional','roto','desbordado','reserva')),
check (cont_tipo in ('volqueta','reciclaje','mezclados')) 
);

create table if not exists camion(
cam_matricula char(7) primary key,
cam_activo boolean default true,
cam_tipo varchar(9),
cam_capacidad int,
cam_modelo varchar(13),
cam_estado varchar(9),
check (cam_estado in('funcional','roto')),
check (cam_modelo in('mercedes-benz','caterpillar')),
check (cam_tipo in('volqueta','reciclaje','mezclados')));

create table if not exists cuadrilla(
cuad_id int auto_increment primary key,
cuad_activa boolean default true,
cuad_cam char(7),
constraint foreign key (cuad_cam) references camion(cam_matricula));

create table if not exists ruta(
ruta_id int auto_increment primary key,
ruta_activo boolean default true,
ruta_tipo varchar(9),
check (ruta_tipo = 'reciclaje' or ruta_tipo = 'mezclados' or ruta_tipo ='volqueta'));

create table if not exists establecimiento(
estab_id int primary key auto_increment,
estab_activo boolean default true,
hora_apertura time,
hora_cierre time,
